package com.sentinel.audit.service;

import com.sentinel.audit.model.Category;
import com.sentinel.audit.model.Confidence;
import com.sentinel.audit.model.Finding;
import com.sentinel.audit.model.Severity;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.*;

class GeneratedFilesTest {

    private static Finding finding(String file) {
        Finding f = new Finding();
        f.setCategory(Category.QUALITY);
        f.setSeverity(Severity.MEDIUM);
        f.setToolSource("ESLint");
        f.setFilePath(file);
        f.setLineNumber(5);
        f.setRuleId("regra-x");
        return f;
    }

    @Test
    void reconheceCabecalhosDeCodigoGerado() {
        assertTrue(GeneratedFiles.hasGeneratedHeader("/*\n * Generated file, DO NOT EDIT\n */\nexport class A {}"));
        assertTrue(GeneratedFiles.hasGeneratedHeader("// Code generated by foo. DO NOT EDIT.\npackage x"));
        assertTrue(GeneratedFiles.hasGeneratedHeader("/** @generated */"));
        assertTrue(GeneratedFiles.hasGeneratedHeader("# This file is auto-generated. Do not modify it."));
    }

    @Test
    void textoComumNaoEhGerado() {
        assertFalse(GeneratedFiles.hasGeneratedHeader("// Gera o relatório e não edita o arquivo\nclass A {}"));
        assertFalse(GeneratedFiles.hasGeneratedHeader("// do not edit this constant by hand\nclass A {}"));
        assertFalse(GeneratedFiles.hasGeneratedHeader(""));
        assertFalse(GeneratedFiles.hasGeneratedHeader(null));
    }

    @Test
    void detectaPeloCabecalhoEBaixaAConfianca(@TempDir Path dir) throws IOException {
        Files.createDirectories(dir.resolve("api"));
        Files.writeString(dir.resolve("api/ClienteApi.ts"), "/* Generated file, DO NOT EDIT */\nlet x: any = 1;\n");
        Files.writeString(dir.resolve("api/Manual.ts"), "let y: any = 2;\n");
        Finding gerado = finding("api/ClienteApi.ts");
        Finding manual = finding("api/Manual.ts");
        Finding fora = finding("../fora.ts");
        List<Finding> todos = List.of(gerado, manual, fora);

        Set<String> detectados = GeneratedFiles.detect(dir, todos);
        assertEquals(Set.of("api/ClienteApi.ts"), detectados);

        FindingConfidence.assessAll(todos, Map.of(), null, detectados);
        assertEquals(Confidence.LOW, gerado.getConfidence());
        assertTrue(gerado.getConfidenceReason().contains("gerado"));
        assertEquals(Confidence.MEDIUM, manual.getConfidence());
    }
}
